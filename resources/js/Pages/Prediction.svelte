<script>
    import { onDestroy } from "svelte";
    import AppHeader from "../Components/AppHeader.svelte";
    import AppSidebar from "../Components/AppSidebar.svelte";

    // Preview-only data. Product options and results will come from Inertia props later.
    const products = [
        { id: 42, name: "Kawasaki Ninja Brake Pad", sku: "BP-KN-004" },
        { id: 27, name: "Yamaha MT-15 Air Filter", sku: "AF-YM-021" },
        { id: 18, name: "Honda Click Drive Belt", sku: "DB-HC-018" },
    ];

    const models = [
        { value: "simple_linear_regression", label: "Simple Linear Regression", helper: "A lightweight trend-based estimate." },
        { value: "random_forest_regression", label: "Random Forest Regression", helper: "A tree-based estimate for richer historical patterns." },
    ];

    let productId = "";
    let modelName = "simple_linear_regression";
    let forecastHorizonDays = "30";
    let errors = {};
    let status = "initial";
    let result = null;
    let runTimer;
    let mobileMenuOpen = false;

    $: selectedProduct = products.find((product) => String(product.id) === productId);
    $: selectedModel = models.find((model) => model.value === modelName);

    function validate() {
        const nextErrors = {};
        if (!productId) nextErrors.product_id = "Select a product to forecast.";
        if (!modelName) nextErrors.model_name = "Select a regression model.";
        const horizon = Number(forecastHorizonDays);
        if (!forecastHorizonDays) nextErrors.forecast_horizon_days = "Enter a forecast horizon.";
        else if (!Number.isInteger(horizon) || horizon < 1 || horizon > 365) nextErrors.forecast_horizon_days = "Enter a whole number from 1 to 365 days.";
        errors = nextErrors;
        return Object.keys(nextErrors).length === 0;
    }

    function runPrediction() {
        result = null;
        status = "initial";
        if (!validate()) {
            status = "validation_error";
            return;
        }

        status = "loading";
        runTimer = window.setTimeout(() => {
            result = {
                forecast_date: "2026-11-27",
                predicted_units: modelName === "random_forest_regression" ? 16.8 : 14.5,
                lower_bound: modelName === "random_forest_regression" ? 11.2 : 10.0,
                upper_bound: modelName === "random_forest_regression" ? 22.4 : 19.0,
                model_name: selectedModel.label,
            };
            status = "result";
        }, 700);
    }

    function resetPrediction() {
        if (runTimer) window.clearTimeout(runTimer);
        productId = "";
        modelName = "simple_linear_regression";
        forecastHorizonDays = "30";
        errors = {};
        result = null;
        status = "initial";
    }

    function startAnother() {
        result = null;
        errors = {};
        status = "initial";
    }

    function showFailurePreview() {
        if (runTimer) window.clearTimeout(runTimer);
        result = null;
        errors = {};
        status = "failure";
    }

    onDestroy(() => {
        if (runTimer) window.clearTimeout(runTimer);
    });
</script>

<svelte:head>
    <title>Prediction | One Prompt Away</title>
</svelte:head>

<div class="flex h-screen min-h-[720px] overflow-hidden bg-slate-50 font-sans text-slate-900">
    <AppSidebar activeItem="Prediction" bind:mobileMenuOpen />
    <div class="flex min-w-0 flex-1 flex-col">
        <AppHeader title="Prediction" bind:mobileMenuOpen />
        <main class="min-h-0 flex-1 overflow-y-auto">
            <div class="mx-auto max-w-[1480px] px-4 py-6 sm:px-8 sm:py-8">
                <div class="mb-7 flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
                    <div>
                        <p class="mb-2 text-xs font-medium text-slate-500">Workspace / Prediction</p>
                        <h1 class="text-2xl font-semibold tracking-tight text-slate-950">Sales prediction</h1>
                        <p class="mt-1 max-w-2xl text-sm text-slate-500">Estimate future product demand using a selected regression model and forecast horizon.</p>
                    </div>
                    <span class="w-fit rounded-full bg-amber-50 px-2.5 py-1 text-[10px] font-semibold text-amber-700">Preview only</span>
                </div>

                <div class="mb-6 flex items-start gap-3 rounded-lg border border-blue-100 bg-blue-50/70 px-4 py-3.5 text-xs text-blue-800">
                    <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" class="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true"><circle cx="12" cy="12" r="9" /><path d="M12 10v6M12 7h.01" /></svg>
                    <p><span class="font-semibold">Preview only —</span> results are sample data and are not generated by a trained model. Product options, model inputs and output definitions still need backend confirmation.</p>
                </div>

                <section class="grid grid-cols-1 gap-6 xl:grid-cols-[minmax(0,0.9fr)_minmax(0,1.1fr)]">
                    <article class="rounded-lg border border-slate-200 bg-white p-5 sm:p-6">
                        <div class="mb-6">
                            <h2 class="text-sm font-semibold text-slate-900">Prediction inputs</h2>
                            <p class="mt-1 text-xs text-slate-500">Choose the scope and method for this preview.</p>
                        </div>
                        {#if status === "validation_error"}
                            <div class="mb-5 rounded-md border border-rose-200 bg-rose-50 px-3.5 py-3 text-xs text-rose-700" role="alert">Review the highlighted fields before running a prediction.</div>
                        {/if}
                        <form class="space-y-5" on:submit|preventDefault={runPrediction}>
                            <div>
                                <label for="prediction-product" class="mb-1.5 block text-xs font-medium text-slate-700">Product <span class="text-rose-600">*</span></label>
                                <select id="prediction-product" bind:value={productId} class:border-rose-300={errors.product_id} class="h-10 w-full rounded-md border border-slate-200 bg-white px-3 text-sm text-slate-700 outline-none focus:border-blue-500 focus:ring-2 focus:ring-blue-100">
                                    <option value="">Select a product</option>
                                    {#each products as product}<option value={product.id}>{product.name} · {product.sku}</option>{/each}
                                </select>
                                <p class="mt-1.5 text-[11px] text-slate-400">Preview product scope; the backend will provide the available catalog.</p>
                                {#if errors.product_id}<p class="mt-1 text-[11px] text-rose-600">{errors.product_id}</p>{/if}
                            </div>

                            <div>
                                <label for="prediction-model" class="mb-1.5 block text-xs font-medium text-slate-700">Regression model <span class="text-rose-600">*</span></label>
                                <select id="prediction-model" bind:value={modelName} class:border-rose-300={errors.model_name} class="h-10 w-full rounded-md border border-slate-200 bg-white px-3 text-sm text-slate-700 outline-none focus:border-blue-500 focus:ring-2 focus:ring-blue-100">
                                    {#each models as model}<option value={model.value}>{model.label}</option>{/each}
                                </select>
                                <p class="mt-1.5 text-[11px] text-slate-400">{selectedModel?.helper} Final model availability is subject to backend confirmation.</p>
                                {#if errors.model_name}<p class="mt-1 text-[11px] text-rose-600">{errors.model_name}</p>{/if}
                            </div>

                            <div>
                                <label for="prediction-horizon" class="mb-1.5 block text-xs font-medium text-slate-700">Forecast horizon <span class="text-rose-600">*</span></label>
                                <div class="relative">
                                    <input id="prediction-horizon" bind:value={forecastHorizonDays} type="number" min="1" max="365" step="1" class:border-rose-300={errors.forecast_horizon_days} class="h-10 w-full rounded-md border border-slate-200 px-3 pr-16 text-sm text-slate-800 outline-none focus:border-blue-500 focus:ring-2 focus:ring-blue-100" />
                                    <span class="pointer-events-none absolute right-3 top-2.5 text-xs text-slate-400">days</span>
                                </div>
                                <p class="mt-1.5 text-[11px] text-slate-400">Enter a whole number from 1 to 365 days for this preview.</p>
                                {#if errors.forecast_horizon_days}<p class="mt-1 text-[11px] text-rose-600">{errors.forecast_horizon_days}</p>{/if}
                            </div>

                            <div class="flex flex-col-reverse gap-2 border-t border-slate-100 pt-5 sm:flex-row sm:justify-end">
                                <button type="button" class="rounded-md border border-slate-200 bg-white px-4 py-2.5 text-xs font-semibold text-slate-600 hover:bg-slate-50" on:click={resetPrediction}>Reset</button>
                                <button type="submit" disabled={status === "loading"} class="flex items-center justify-center gap-2 rounded-md bg-slate-900 px-4 py-2.5 text-xs font-semibold text-white transition-colors hover:bg-slate-700 disabled:cursor-not-allowed disabled:opacity-60">
                                    {#if status === "loading"}<span class="h-3.5 w-3.5 animate-spin rounded-full border-2 border-white/40 border-t-white"></span>Preparing preview...{:else}Run prediction{/if}
                                </button>
                            </div>
                        </form>
                    </article>

                    <article class="rounded-lg border border-slate-200 bg-white p-5 sm:p-6">
                        <div class="flex items-start justify-between gap-4">
                            <div><h2 class="text-sm font-semibold text-slate-900">Prediction result</h2><p class="mt-1 text-xs text-slate-500">Illustrative output for the selected product.</p></div>
                            {#if status === "result"}<span class="rounded-full bg-emerald-50 px-2 py-1 text-[10px] font-semibold text-emerald-700">Sample result</span>{/if}
                        </div>
                        {#if status === "initial" || status === "validation_error"}
                            <div class="flex min-h-[360px] flex-col items-center justify-center px-4 text-center">
                                <div class="flex h-11 w-11 items-center justify-center rounded-full bg-slate-100 text-slate-400"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" class="h-5 w-5" aria-hidden="true"><path d="M4 19V5m0 14h16" /><path d="m7 15 3-4 3 2 5-7" /></svg></div>
                                <h3 class="mt-3 text-sm font-semibold text-slate-800">No prediction yet</h3>
                                <p class="mt-1 max-w-xs text-xs leading-5 text-slate-500">Select the required inputs and run the preview to see an example forecast.</p>
                                <button type="button" class="mt-5 text-[11px] font-semibold text-slate-400 underline decoration-slate-300 underline-offset-2 hover:text-slate-600" on:click={showFailurePreview}>Preview unavailable state</button>
                            </div>
                        {:else if status === "loading"}
                            <div class="flex min-h-[360px] flex-col items-center justify-center text-center" aria-live="polite">
                                <span class="h-7 w-7 animate-spin rounded-full border-2 border-blue-100 border-t-blue-600"></span>
                                <h3 class="mt-4 text-sm font-semibold text-slate-800">Preparing sample result</h3>
                                <p class="mt-1 text-xs text-slate-500">No trained model is being called.</p>
                            </div>
                        {:else if status === "failure"}
                            <div class="flex min-h-[360px] flex-col items-center justify-center px-4 text-center">
                                <div class="flex h-11 w-11 items-center justify-center rounded-full bg-rose-50 text-rose-600"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" class="h-5 w-5" aria-hidden="true"><path d="M12 3 3.5 19h17L12 3Z" /><path d="M12 9v4M12 16h.01" /></svg></div>
                                <h3 class="mt-3 text-sm font-semibold text-slate-800">Prediction unavailable</h3>
                                <p class="mt-1 max-w-xs text-xs leading-5 text-slate-500">This is a preview failure state. A backend error, unavailable model or insufficient data should provide the final message here.</p>
                                <button type="button" class="mt-5 rounded-md border border-slate-200 bg-white px-4 py-2.5 text-xs font-semibold text-slate-600 hover:bg-slate-50" on:click={startAnother}>Try again</button>
                            </div>
                        {:else if status === "result"}
                            <div class="mt-6">
                                <div class="rounded-md border border-blue-100 bg-blue-50/60 p-4">
                                    <p class="text-xs text-blue-700">{selectedProduct?.name}</p>
                                    <div class="mt-2 flex flex-wrap items-end gap-2"><span class="text-3xl font-semibold tracking-tight text-slate-950">{result.predicted_units}</span><span class="mb-1 text-xs text-slate-500">predicted units</span></div>
                                    <p class="mt-2 text-[11px] text-slate-500">Forecast date: <span class="font-medium text-slate-700">{result.forecast_date}</span></p>
                                </div>
                                <div class="mt-5 grid grid-cols-1 gap-3 sm:grid-cols-3">
                                    <div class="rounded-md border border-slate-200 p-3"><p class="text-[10px] uppercase tracking-wide text-slate-400">Lower bound</p><p class="mt-1 text-lg font-semibold text-slate-900">{result.lower_bound}</p><p class="text-[10px] text-slate-400">units</p></div>
                                    <div class="rounded-md border border-slate-200 p-3"><p class="text-[10px] uppercase tracking-wide text-slate-400">Model</p><p class="mt-1 text-xs font-semibold leading-5 text-slate-900">{result.model_name}</p></div>
                                    <div class="rounded-md border border-slate-200 p-3"><p class="text-[10px] uppercase tracking-wide text-slate-400">Upper bound</p><p class="mt-1 text-lg font-semibold text-slate-900">{result.upper_bound}</p><p class="text-[10px] text-slate-400">units</p></div>
                                </div>
                                <div class="mt-5 flex items-start gap-2 rounded-md border border-amber-100 bg-amber-50 px-3.5 py-3 text-[11px] leading-5 text-amber-800"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" class="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true"><path d="M12 3 3.5 19h17L12 3Z" /><path d="M12 9v4M12 16h.01" /></svg><span>Illustrative values only. Bounds, evaluation metrics and stock recommendations are not defined by the current frontend requirements.</span></div>
                                <button type="button" class="mt-5 w-full rounded-md border border-slate-200 bg-white px-4 py-2.5 text-xs font-semibold text-slate-600 hover:bg-slate-50" on:click={startAnother}>Start another prediction</button>
                            </div>
                        {/if}
                    </article>
                </section>
            </div>
        </main>
    </div>
</div>
